param([Parameter(Mandatory=$true)][string]$FontPath,[switch]$Chinese,[switch]$Countdown)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
if ($Chinese -and $Countdown) { throw 'Choose one atlas to generate.' }
if ($Chinese) {
  $expectedHash = 'A3041811A78C361B1DE50F953C805E0244951C21C5BD412F7232EF0D899AF0DA'
  $fontName = 'Noto Sans SC'
  $source = 'https://github.com/google/fonts/tree/main/ofl/notosanssc'
  $chars = '红蓝方弹药热量回合准备仅可旋转和瞄已暂停结束止胜利平局双过损毁：'
  $sizes = [ordered]@{label=17; score=24; result=31}
  $advanceRatio = 1
  $exportPrefix = 'hudChinese'
  $outputName = 'hud-chinese-atlas.ts'
} else {
  $expectedHash = 'D3C38E55C78F5B0F28009FDDBA4834EC503278936A5986032424C9BD2D23AA46'
  $fontName = 'IBM Plex Mono SemiBold'
  $source = 'https://github.com/google/fonts/tree/main/ofl/ibmplexmono'
  $chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 :/.-'
  $sizes = [ordered]@{label=16; score=28; result=33}
  $advanceRatio = 0.6
  $exportPrefix = 'hud'
  $outputName = 'hud-atlas.ts'
  if ($Countdown) {
    $chars = '12345'
    $sizes = [ordered]@{countdown=128}
    $exportPrefix = 'hudCountdown'
    $outputName = 'hud-countdown-atlas.ts'
  }
}
$resolvedFont = (Resolve-Path -LiteralPath $FontPath).Path
if ((Get-FileHash -LiteralPath $resolvedFont).Hash -ne $expectedHash) {
  throw "Expected the pinned $fontName TTF."
}
$fonts = [Drawing.Text.PrivateFontCollection]::new()
$fonts.AddFontFile($resolvedFont)
$family = $fonts.Families[0]
$lines = @(
  "// Generated by scripts/generate-hud-font.ps1 from $fontName (OFL 1.1).",
  "// Source: $source",
  "// TTF SHA-256: $expectedHash",
  "export const ${exportPrefix}Characters = '$chars';",
  "export const ${exportPrefix}Atlas = {"
)
$format = [Drawing.StringFormat]::GenericTypographic
foreach ($size in $sizes.GetEnumerator()) {
  $advance = [int][Math]::Round($size.Value * $advanceRatio)
  $glyphs = foreach ($char in $chars.ToCharArray()) {
    $path = [Drawing.Drawing2D.GraphicsPath]::new()
    if ($char -ne ' ') {
      $path.AddString([string]$char,$family,0,$size.Value,[Drawing.PointF]::Empty,$format)
    }
    $path
  }
  $bounds = $glyphs | Where-Object PointCount -gt 0 | ForEach-Object { $_.GetBounds() }
  $top = [int][Math]::Floor(($bounds | Measure-Object -Property Top -Minimum).Minimum)
  $bottom = [int][Math]::Ceiling(($bounds | Measure-Object -Property Bottom -Maximum).Maximum)
  $height = $bottom - $top
  $coverage = [Collections.Generic.List[byte]]::new()
  foreach ($glyph in $glyphs) {
    $bitmap = [Drawing.Bitmap]::new($advance,$height)
    $g = [Drawing.Graphics]::FromImage($bitmap)
    $g.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.TranslateTransform(0,-$top)
    $g.FillPath([Drawing.Brushes]::White,$glyph)
    for ($y=0; $y -lt $height; $y++) {
      for ($x=0; $x -lt $advance; $x++) {
        $coverage.Add([byte][Math]::Round($bitmap.GetPixel($x,$y).A * 4 / 255))
      }
    }
    $g.Dispose()
    $bitmap.Dispose()
    $glyph.Dispose()
  }
  $packed = [byte[]]::new([Math]::Ceiling($coverage.Count / 2))
  for ($i=0; $i -lt $coverage.Count; $i++) {
    $packed[$i -shr 1] = $packed[$i -shr 1] -bor ($coverage[$i] -shl (4 * ($i % 2)))
  }
  $encoded = [Convert]::ToBase64String($packed)
  $lines += "  $($size.Key): [$advance, $height, '$encoded'],"
}
$lines += '} as const;'
$format.Dispose()
$fonts.Dispose()
$output = Join-Path $PSScriptRoot "../src/shared/$outputName"
[IO.File]::WriteAllLines($output,$lines)
